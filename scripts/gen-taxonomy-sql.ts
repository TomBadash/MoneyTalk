// Generates supabase/migrations/0004_seed_taxonomy.sql from src/classify/taxonomy.ts
// so the DB and the classifier share one source of truth.  Run: npm run gen:taxonomy
import { writeFileSync } from "node:fs";
import { taxonomyNodes } from "../src/classify/taxonomy.ts";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const nodes = taxonomyNodes();
const order = { parent: 0, category: 1, subcategory: 2 } as const;
const rows = nodes
  .sort((a, b) => order[a.level] - order[b.level])
  .map((n) => `(${q(n.id)}, null, ${q(n.parentId)}, ${q(n.level)}, ${q(n.he)}, ${q(n.icon)}, ${q(n.color)}, ${q(n.consumptionType)}, ${q(n.financialType)})`);
writeFileSync(
  new URL("../supabase/migrations/0004_seed_taxonomy.sql", import.meta.url),
  `-- GENERATED by scripts/gen-taxonomy-sql.ts — do not edit by hand.\n` +
    `insert into public.categories (id, user_id, parent_id, level, name_he, icon, color, consumption_type, financial_type) values\n${rows.join(",\n")}\non conflict (id) do update set name_he = excluded.name_he, color = excluded.color, icon = excluded.icon,\n  consumption_type = excluded.consumption_type, financial_type = excluded.financial_type, parent_id = excluded.parent_id;\n`,
);
